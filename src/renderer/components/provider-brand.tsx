export const providerName = (provider: string): string =>
  Object.entries(brands).find(([, brand]) =>
    brand.providers.some((alias) => alias === provider.trim().toLowerCase()),
  )?.[0] ?? provider

const styles = stylex.create({
  brand: { alignItems: "center", display: "inline-flex", flexShrink: 0, gap: 6 },
  hidden: {
    clipPath: "inset(50%)",
    height: 1,
    overflow: "hidden",
    position: "absolute",
    whiteSpace: "nowrap",
    width: 1,
  },
  icon: { flexShrink: 0, height: 16, width: 16 },
})

export const ProviderBrand = ({
  provider,
  label = false,
}: {
  provider: string
  label?: boolean
}) => {
  const name = providerName(provider)
  const brand = Object.entries(brands).find(([key]) => key === name)?.[1]
  return (
    <span {...stylex.props(styles.brand)}>
      {brand ? (
        <svg
          aria-hidden="true"
          focusable="false"
          viewBox={brand.viewBox}
          {...stylex.props(styles.icon)}
        >
          {brand.paths.map((path) => (
            <path key={path} fill="currentColor" d={path} />
          ))}
        </svg>
      ) : null}
      {label ? <span>{name}</span> : <span {...stylex.props(styles.hidden)}>{name}</span>}
      {!brand && !label ? <span aria-hidden="true">{name.slice(0, 2)}</span> : null}
    </span>
  )
}
